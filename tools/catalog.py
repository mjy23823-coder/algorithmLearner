CATALOG = {p["id"]: p for p in PROBLEMS}


def frequency_label(p):
    return {3: "大厂高频", 2: "常见题"}.get(p["frequency"], "专题补充")


def family(topic):
    topic = (topic or "").strip()
    return FAMILY.get(topic, topic)


def related(topic, current):
    """题目专题是否属于当前学习专题，例如“固定窗口”属于“双指针与滑动窗口”。"""
    if not topic or not current:
        return False
    names = {topic, family(topic)}
    return any(name and (name in current or current in name) for name in names) or family(current) == family(topic)


def line_position(current):
    """当前专题在主线中的位置；跨多个专题时取最靠后的一个。"""
    hits = [i for i, name in enumerate(MAIN_LINE) if name in (current or "") or family(current) == name]
    return max(hits) if hits else 0


def candidates(current, excluded, limit=4, has_exercise=None):
    """推荐待学新题：当前专题最多 2 道收尾题，其余名额按主线进入下一个专题。"""
    excluded = set(excluded)
    position = line_position(current)
    current_topics = [name for name in MAIN_LINE if related(name, current)] or [MAIN_LINE[position]]
    later = [name for name in MAIN_LINE[position + 1:] if name not in current_topics]
    level = {"Easy": 0, "Medium": 1, "Hard": 2}
    runnable = has_exercise or (lambda pid: False)

    def ranked(topics):
        pool = [p for p in PROBLEMS if p["topic"] in topics and p["id"] not in excluded]
        return sorted(pool, key=lambda p: (not runnable(p["id"]), level[p["difficulty"]] == 2, -p["frequency"],
                                           level[p["difficulty"]], int(p["id"])))

    chosen = [(p, "收尾当前专题") for p in ranked(current_topics)[:2]]
    for topic in later:
        if len(chosen) >= limit:
            break
        chosen += [(p, f"主线下一专题「{topic}」") for p in ranked([topic])[:limit - len(chosen)]]
    picks = []
    for p, stage in chosen[:limit]:
        # 推荐理由不写解法要点，避免在用户先解释思路前泄露关键提示。
        why = [stage, f"{p['difficulty']} · {frequency_label(p)}"]
        if not runnable(p["id"]):
            why.append("工作台暂无本地用例，可由聊天教练检查")
        picks.append({**p, "reason": why, "workbench": runnable(p["id"])})
    return picks
